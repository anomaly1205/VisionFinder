"""Shared paths and settings for the VisionFinder backend."""
import os

BACKEND = os.path.dirname(os.path.abspath(__file__))
FRONTEND = os.path.normpath(os.path.join(BACKEND, "..", "frontend"))
PRODUCTS_JSON = os.path.join(FRONTEND, "data", "products.json")
HOLDOUT_JSON = os.path.join(FRONTEND, "data", "holdout.json")

MODEL = os.environ.get("VF_MODEL", "ViT-B-32")
PRETRAINED = os.environ.get("VF_PRETRAINED", "laion2b_s34b_b79k")

DATA_DIR = os.path.join(BACKEND, "data")  # generated by build_index.py, gitignored
INDEX_PATH = os.path.join(DATA_DIR, f"{MODEL}_{PRETRAINED}.faiss")  # one index per model
IDS_PATH = os.path.join(DATA_DIR, f"{MODEL}_{PRETRAINED}.ids.json")

# Confidence of an image search, from the best image score (defaults picked by evaluate.py):
#   >= HIGH -> "high" (match), >= LOW -> "medium" (similar pieces), else "low" (no confident match).
# HIGH maximises correct accepts minus false accepts; LOW is the lowest threshold with precision >= 60%.
THRESHOLD_HIGH = float(os.environ.get("VF_THRESHOLD", 0.825))
THRESHOLD_LOW = float(os.environ.get("VF_THRESHOLD_LOW", 0.70))
MAX_UPLOAD = 10 * 1024 * 1024  # bytes

CORS_ORIGINS = [f"http://{h}:{p}" for h in ("127.0.0.1", "localhost") for p in (5500, 5501)]


def image_path(rel):
    """Product JSON stores image paths relative to frontend/."""
    return os.path.join(FRONTEND, rel)
